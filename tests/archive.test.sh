#!/bin/bash
# The page a session gets from its archive, once Claude Code has deleted the
# transcript, is the page it had while the transcript was there: the same
# messages, the same prompts, the same title, the same search and the same
# tokens. The archive is written by the real save, as a hook runs it, and
# the transcript is then taken away and the pages built again.
#
# Then the archives written before that was so (format 4 and older): one
# whose transcript is still here is written again by the next save, and one
# whose transcript has gone is shown without what the harness put in it.
#
#   bash tests/archive.test.sh
set -u

. "$(dirname "$0")/lib.sh"

HERE="$(cd "$(dirname "$0")/.." && pwd)"
pass=0; fail=0
check() {
  if [ "$2" = "$3" ]; then pass=$((pass + 1)); printf '  ok    %s\n' "$1"
  else fail=$((fail + 1)); printf '  FAIL  %s (expected %s, got %s)\n' "$1" "$3" "$2"; fi
}
T="$(cd "$(tmpdir charchive)" && pwd -P)"
trap 'rm -rf "$T"' EXIT

ID=aaaaaaaa-1111-2222-3333-444444444444
OLD=bbbbbbbb-1111-2222-3333-444444444444
AF="$(. "$HERE/release.sh"; printf '%s' "$CH_ARCHIVE_FORMAT")"

# A transcript with every case the two readers once read differently:
# harness context, the harness's tags in a prompt, a slash command, Claude
# Code's own title, pictures in a prompt and in a tool's output, output and
# thinking past what the page shows with an emoji where it is cut, a tool
# input past its bound, side remarks, a secret, tokens and a cost.
fixture() {   # transcript, cwd
  node -e '
    var fs = require("fs"), out = process.argv[1], cwd = process.argv[2], id = process.argv[3];
    var n = 0;
    function at(m) { return new Date(Date.UTC(2026, 10, 6, 9, m)).toISOString(); }
    function rec(o) { n++; return JSON.stringify(Object.assign({ cwd: cwd, sessionId: id, uuid: "r" + n }, o)) + "\n"; }
    function user(m, content, extra) { return rec(Object.assign({ type: "user", timestamp: at(m), message: { role: "user", content: content } }, extra || {})); }
    function reply(m, mid, content, extra) {
      return rec(Object.assign({ type: "assistant", timestamp: at(m), message: { id: mid, role: "assistant", model: "claude-opus-5",
        content: content, usage: { input_tokens: m + 1, output_tokens: 2 * m + 1, cache_read_input_tokens: 5, cache_creation_input_tokens: 1 } } }, extra || {}));
    }
    var F = require(process.argv[4] + "/tests/fake-secrets.js");
    var gh = F.cases.filter(function (c) { return c.rule === "github"; })[0];
    var pw = F.cases.filter(function (c) { return c.rule === "url-password"; })[0];
    fs.writeFileSync(process.argv[5], gh.secret + "\n" + pw.secret + "\n");
    var long = new Array(6000).join("x") + "🙂🙂" + new Array(900).join("é");
    var s = rec({ type: "permission-mode", permissionMode: "default" });
    s += user(0, "<command-name>/clear</command-name><command-args></command-args>");
    s += user(1, "Caveat: The messages below were generated by the user while running local commands.", { isMeta: true });
    s += user(1, "<system-reminder>harness context, not typed</system-reminder>Fix the weather app, " + gh.text);
    s += rec({ type: "summary", aiTitle: "Claude\u0027s own title" });
    s += reply(2, "msg_1", [{ type: "thinking", thinking: long }, { type: "text", text: "Looking." },
      { type: "tool_use", id: "toolu_1", name: "Edit", input: { file_path: "/w/a.js", old_string: new Array(25000).join("o"), new_string: "n" } },
      { type: "tool_use", id: "toolu_2", name: "TodoWrite", input: { todos: [{ content: "one", status: "completed" }, { content: "two", status: "pending" }] } },
      { type: "tool_use", id: "toolu_3", name: "Task", input: { description: "check", prompt: new Array(2500).join("p"), subagent_type: "general-purpose" } }]);
    s += user(3, [{ type: "tool_result", tool_use_id: "toolu_1", content: [{ type: "text", text: "edited" }, { type: "image", source: {} }] }]);
    s += user(3, [{ type: "tool_result", tool_use_id: "toolu_2", content: long }]);
    s += user(3, [{ type: "tool_result", tool_use_id: "toolu_3", content: "done" }]);
    s += reply(4, "msg_2", [{ type: "tool_use", id: "toolu_4", name: "Bash", input: { command: "psql " + pw.text, description: "call" } }]);
    s += user(5, [{ type: "tool_result", tool_use_id: "toolu_4", content: "ok" }]);
    s += user(6, [{ type: "image", source: {} }, { type: "text", text: "and this picture" }]);
    s += reply(7, "msg_3", [{ type: "text", text: "a side remark" }], { isSidechain: true });
    s += user(7, "a side prompt", { isSidechain: true });
    s += reply(8, "msg_4", [{ type: "text", text: "All done." }]);
    s += user(9, "[Request interrupted by user]");
    s += rec({ type: "cost-state", startTime: Date.UTC(2026, 10, 6, 8), modelUsage: { "claude-opus-5": { costUSD: 0.42 } } });
    fs.writeFileSync(out, s);' "$1" "$2" "$ID" "$HERE" "$T/probes"
}

# Everything a page, the index, the search and the dashboard say about a
# session, as one JSON line per field.
said() {   # out, id
  node -e '
    var fs = require("fs"), o = process.argv[1], id = process.argv[2];
    var page = fs.readFileSync(o + "/sessions/" + id + ".html", "utf8");
    var d = JSON.parse(/<script type="application\/json" id="session-data">([\s\S]*?)<\/script>/.exec(page)[1]);
    var idx = fs.readFileSync(o + "/index.html", "utf8");
    var x = JSON.parse(/id="index-data">([\s\S]*?)<\/script>/.exec(idx)[1]).sessions.filter(function (s) { return s.id === id; })[0] || {};
    var m = JSON.parse(fs.readFileSync(o + "/.manifest.json", "utf8"))[id] || {};
    console.log("messages " + JSON.stringify(d.messages));
    console.log("title " + JSON.stringify(d.meta.title));
    console.log("index " + JSON.stringify([x.title, x.prompts, x.tok]));
    console.log("prompts " + JSON.stringify(m.prompts));
    console.log("usage " + JSON.stringify(m.usage));
    console.log("search " + fs.readFileSync(o + "/search/" + id + ".js", "utf8").trim());
    console.log("kind " + d.meta.kind);' "$1" "$2"
}
field() { sed -n "s/^$1 //p" "$2"; }

ENGINES=node; [ "$HAVE_OSASCRIPT" = true ] && ENGINES="osascript node"
for ENG in $ENGINES; do
  H="$T/$ENG/home"; ROOT="$T/$ENG/root"; APP="$ROOT/weather-app"
  PROJ="$H/.claude/projects/$(printf '%s' "$APP" | tr '/' '-')"
  CONV="$APP/.claude/.claude-conversations"
  mkdir -p "$PROJ" "$APP"
  J="$PROJ/$ID.jsonl"
  fixture "$J" "$APP"
  run() {   # what the hook and the command run, in this sandbox
    env HOME="$H" CLAUDE_HTML_CONF="$H/.claude/claude-html.conf" CLAUDE_HTML_ROOT="$ROOT" \
      CLAUDE_HTML_ENGINE="$ENG" "$@"
  }
  save() {   # the session-end save, as Claude Code runs it, run to its end
    (cd "$APP" && printf '{"session_id":"%s","transcript_path":"%s","hook_event_name":"SessionEnd"}' "$ID" "$J" |
      run CLAUDE_HTML_OUT="$T/$ENG/out-save" CLAUDE_HTML_DETACHED=1 bash "$HERE/save-conversation.sh" >/dev/null 2>&1)
  }
  build() {   # out
    run bash -c '. "$0/conf.sh" 2>/dev/null; . "$0/platform.sh"; ch_pick_engine
      ch_js "$0/convert.js" "{\"root\":\"$1\",\"out\":\"$2\",\"here\":\"$0\"}"' "$HERE" "$ROOT" "$1" >/dev/null 2>&1
  }

  # ── the archive is the transcript ──
  save
  check "$ENG: the real save writes the archive, in format $AF" \
    "$(sed -n 's/^{"sourceBytes":[0-9]*,"format":\([0-9]*\),.*/\1/p' "$CONV/$ID.json")" "$AF"
  build "$T/$ENG/out-t"
  said "$T/$ENG/out-t" "$ID" > "$T/$ENG/t"
  mv "$J" "$T/$ENG/away.jsonl"
  build "$T/$ENG/out-a"
  said "$T/$ENG/out-a" "$ID" > "$T/$ENG/a"
  check "$ENG: built from the transcript, then from the archive alone" \
    "$(field kind "$T/$ENG/t") $(field kind "$T/$ENG/a")" "transcript archive"
  for f in messages title index prompts usage search; do
    if [ "$(field $f "$T/$ENG/t")" = "$(field $f "$T/$ENG/a")" ]; then r=same; else r=differ; fi
    check "$ENG:   the same $f" "$r" same
  done
  check "$ENG:   Claude Code's own title, and four prompts, the side one left out" \
    "$(field title "$T/$ENG/a") $(field prompts "$T/$ENG/a")" "\"Claude's own title\" 4"
  check "$ENG:   no harness text, no secret, in either" \
    "$(cat "$T/$ENG/t" "$T/$ENG/a" | grep -c -F -e 'harness context' -e 'Caveat: The messages' -e 'command-name' -f "$T/probes")" 0

  # ── archives from before ──
  # One whose transcript is still here is written again, in this format.
  mv "$T/$ENG/away.jsonl" "$J"
  node -e 'var fs=require("fs"),p=process.argv[1],a=JSON.parse(fs.readFileSync(p,"utf8"));
    var o={sourceBytes:a.sourceBytes,format:4,redact:a.redact};
    Object.keys(a).forEach(function(k){ if(!(k in o)) o[k]=a[k]; }); delete o.title;
    fs.writeFileSync(p, JSON.stringify(o));' "$CONV/$ID.json"
  save
  check "$ENG: a format-4 archive whose transcript is here is written again by the next save" \
    "$(sed -n 's/^{"sourceBytes":[0-9]*,"format":\([0-9]*\),.*/\1/p' "$CONV/$ID.json") $(grep -c "Claude's own title" "$CONV/$ID.json")" "$AF 1"

  # One whose transcript has gone, as the archiver wrote it then: the
  # harness's tags kept in a prompt, a slash command as a prompt.
  printf '{"sourceBytes":9,"format":4,"redact":"off","sessionId":"%s","project":"%s","messages":[%s]}\n' "$OLD" "$APP" \
    '{"role":"user","timestamp":"2026-11-01T10:00:00Z","text":"<command-name>/clear</command-name><command-args></command-args>"},{"role":"user","timestamp":"2026-11-01T10:00:01Z","text":"<system-reminder>harness context, not typed</system-reminder>What is the forecast?"},{"role":"assistant","timestamp":"2026-11-01T10:00:02Z","text":"Sunny.","tools":[{"name":"Bash","input":{"command":"ls"}}]},{"role":"tool_result","timestamp":"2026-11-01T10:00:03Z","text":"a.txt"}' \
    > "$CONV/$OLD.json"
  build "$T/$ENG/out-old"
  said "$T/$ENG/out-old" "$OLD" > "$T/$ENG/o"
  check "$ENG: an orphaned format-4 archive shows no harness text" \
    "$(grep -c 'harness context\|command-name' "$T/$ENG/out-old/sessions/$OLD.html") $(grep -c 'harness context' "$T/$ENG/out-old/search/$OLD.js")" "0 0"
  check "$ENG:   its title is the prompt, and it has one" \
    "$(field title "$T/$ENG/o") $(field prompts "$T/$ENG/o") $(field kind "$T/$ENG/o")" '"What is the forecast?" 1 archive'
done

echo
echo "  $pass passed, $fail failed"
[ "$fail" -eq 0 ]
